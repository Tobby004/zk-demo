// test/merkletree.test.js
// Proves the on-chain incremental Merkle tree produces the SAME root as the
// JavaScript tree (scripts/merkleTree.js) your circuit and frontend use.
// Run: npx hardhat test
const { expect } = require("chai");
const hre = require("hardhat");
const { poseidonContract } = require("circomlibjs");
const {
  buildHasher,
  commitmentHash,
  generateNote,
  MerkleTree,
} = require("../../scripts/merkleTree");

const LEVELS = 20;

describe("MerkleTreeWithHistory", function () {
  it("on-chain Poseidon and root match the JS Merkle tree", async function () {
    this.timeout(180000);
    const [signer] = await hre.ethers.getSigners();
    const hasher = await buildHasher();

    // Deploy the Poseidon(2) hasher from circomlibjs-generated bytecode.
    const Hasher = new hre.ethers.ContractFactory(
      poseidonContract.generateABI(2),
      poseidonContract.createCode(2),
      signer
    );
    const poseidon = await Hasher.deploy();
    await poseidon.waitForDeployment();

    // on-chain Poseidon == JS Poseidon
    const onchainH = (
      await poseidon["poseidon(uint256[2])"](["12345", "67890"])
    ).toString();
    expect(onchainH).to.equal(hasher.hash(["12345", "67890"]));

    // Deploy the tree (TestTree exposes insert()).
    const TestTree = await hre.ethers.getContractFactory("TestTree");
    const tree = await TestTree.deploy(LEVELS, await poseidon.getAddress());
    await tree.waitForDeployment();

    // Empty-tree root parity.
    const jsEmpty = new MerkleTree(hasher, LEVELS, []);
    expect((await tree.getLastRoot()).toString()).to.equal(jsEmpty.root());

    // Insert a few deposits and check the root still matches the JS tree.
    const notes = [generateNote(), generateNote(), generateNote(), generateNote()];
    const leaves = notes.map((n) => commitmentHash(hasher, n.nullifier, n.secret));
    for (const leaf of leaves) {
      await (await tree.insert(leaf)).wait();
    }

    const jsTree = new MerkleTree(hasher, LEVELS, leaves);
    expect((await tree.getLastRoot()).toString()).to.equal(jsTree.root());
    expect(await tree.isKnownRoot(jsTree.root())).to.equal(true);
  });
});